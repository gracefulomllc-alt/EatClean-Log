import { scaleIngredient as sc, fmtQty, tagsFor, swapsFor, applySwaps, TAG_FILTERS } from "../src/mealTools.js";
import { MEAL_LIBRARY } from "../src/mealLibrary.js";
let ok = 0, bad = 0; const t = (c, m) => { if (c) ok++; else { bad++; console.log("FAIL", m); } };
const eq = (a, b, m) => t(a === b, `${m}: got "${a}", wanted "${b}"`);
eq(sc("6 oz chicken breast", 2), "12 oz chicken breast", "double oz");
eq(sc("1 cup cooked rice", 2), "2 cups cooked rice", "cup plural");
eq(sc("2 cups broccoli", 0.5), "1 cup broccoli", "cups to cup");
eq(sc("1/2 cup black beans", 2), "1 cup black beans", "fraction doubles to whole");
eq(sc("1 1/2 cups rice", 2), "3 cups rice", "mixed number");
eq(sc("1 cup rice", 1.5), "1 1/2 cups rice", "1.5 cups");
eq(sc("3/4 cup rice", 2), "1 1/2 cups rice", "3/4 doubled");
eq(sc("1 can chickpeas", 3), "3 cans chickpeas", "can");
eq(sc("2 eggs", 2), "4 eggs", "eggs");
eq(sc("1 egg", 3), "3 eggs", "egg plural");
eq(sc("4 skinless chicken thighs", 0.5), "2 skinless chicken thighs", "no false plural change");
eq(sc("salt, pepper, garlic powder", 4), "salt, pepper, garlic powder", "no number: unchanged");
eq(sc("2 tbsp soy sauce", 3), "6 tbsp soy sauce", "tbsp");
eq(sc("1 tsp olive oil", 0.25), "1/4 tsp olive oil", "tiny amounts floor at 1/4");
eq(sc("12 oz chicken", 1), "12 oz chicken", "x1 unchanged");
eq(sc("1.5 cups lentils", 2), "3 cups lentils", "decimal");
eq(fmtQty(2.34), "2 1/3", "thirds");
eq(fmtQty(12.4), "12", "big numbers round");
// tags
const rice = MEAL_LIBRARY.find((m) => /rice, and broccoli|rice and broccoli/i.test(m.name));
t(tagsFor(rice).includes("High protein"), "chicken rice broccoli is high protein");
t(!tagsFor(rice).includes("Vegetarian"), "chicken meal isn't vegetarian");
const veg = MEAL_LIBRARY.find((m) => /Lentil/i.test(m.name));
t(tagsFor(veg).includes("Vegetarian") && tagsFor(veg).includes("No dairy"), "lentil soup: vegetarian and no dairy");
t(MEAL_LIBRARY.every((m) => tagsFor(m).every((x) => typeof x === "string")), "all library meals tag cleanly");
t(TAG_FILTERS.every((f) => MEAL_LIBRARY.some((m) => tagsFor(m).includes(f))), "every filter chip has meals");
t(tagsFor({ name: "Quesadilla", tags: "cheese tortilla", calories: 500, protein: 20, carbs: 40, fat: 20 }).includes("No dairy") === false, "cheese means not 'No dairy'");
// swaps
const cr = swapsFor(rice).find((s) => s.id === "cauli");
t(cr, "rice meal offers cauliflower rice");
const sw = applySwaps(rice, ["cauli"]);
t(sw.calories === rice.calories - 180 && sw.carbs === rice.carbs - 40, "swap changes the numbers");
t(/cauliflower rice/.test(sw.name) && sw.recipe.ingredients[0].startsWith("Swap:"), "name and recipe note updated");
t(!swapsFor(sw).some((s) => s.id === "cauli"), "already-swapped option disappears");
t(applySwaps(rice, ["cauli", "cauli"]).calories === sw.calories, "same swap twice counts once");
t(applySwaps(rice, ["nope"]).calories === rice.calories, "unknown swap ignored");
t(applySwaps({ name: "x", calories: 100, protein: 5, carbs: 5, fat: 1 }, ["cauli"]).calories >= 0 && applySwaps({ name: "x rice", calories: 100, protein: 1, carbs: 5, fat: 1 }, ["cauli"]).calories === 0, "never negative");
const withMayo = MEAL_LIBRARY.find((m) => swapsFor(m).some((s) => s.id === "yogurt"));
t(withMayo || true, "optional mayo meal");
t(MEAL_LIBRARY.filter((m) => swapsFor(m).length).length >= 12, "swaps available on many meals (" + MEAL_LIBRARY.filter((m) => swapsFor(m).length).length + ")");
console.log(ok, "ok", bad, "bad");
