const fs=require("fs"),vm=require("vm");const sb={};vm.createContext(sb);
vm.runInContext(fs.readFileSync(process.argv[2],"utf8")+";this.T={toLocalInput,fromLocalInput,checkFastStart,fastRecord,saveFastIn,MAX_FAST_H}",sb);const T=sb.T;
let ok=0,bad=0;const t=(c,m)=>{if(c)ok++;else{bad++;console.log("FAIL",m)}};
const H=36e5,now=Date.UTC(2026,9,12,20,0,0);
t(T.fromLocalInput(T.toLocalInput(now))===Math.floor(now/6e4)*6e4,"local input round trip");
t(T.fromLocalInput("")===null&&T.fromLocalInput("garbage")===null,"bad input is null");
t(T.checkFastStart(now-5*H,now)==="","start 5h ago is fine");
t(T.checkFastStart(now+H,now)!=="","future start rejected");
t(T.checkFastStart(now-8*24*H,now)!=="","over 7 days rejected");
t(T.checkFastStart(NaN,now)!=="","NaN rejected");
const r=T.fastRecord(now-16*H,now,null,now);
t(r.rec&&r.rec.hours===16&&r.rec.start===now-16*H&&r.rec.end===now,"16h record");
t(r.rec.id===String(now)&&typeof r.rec.u==="number","new record gets a stable id");
t(T.fastRecord(now,now-H,null,now).error,"end before start rejected");
t(T.fastRecord(now-H,now+H,null,now).error,"future end rejected");
t(T.fastRecord(now-9*24*H,now,null,now).error,"too long rejected");
t(T.fastRecord(null,now,null,now).error,"missing start rejected");
// editing keeps the id even when the end time moves, so sync won't duplicate it
const old={end:now-20*H,hours:14};
const e=T.fastRecord(now-34*H,now-18*H,old,now);
t(e.rec.id===String(old.end),"old record (no id) keeps its old key");
const list=T.saveFastIn([old,{id:"b",end:now-50*H,hours:12}],e.rec,String(old.end));
t(list.length===2&&list[0].end===now-18*H&&list.some(f=>f.id==="b"),"edit replaces, doesn't duplicate; sorted newest first");
const added=T.saveFastIn(list,{id:"new",start:now-10*H,end:now-2*H,hours:8,u:now},null);
t(added.length===3&&added[0].id==="new","adding a forgotten fast");
const many=Array.from({length:40},(_,i)=>({id:"x"+i,end:now-i*H}));
t(T.saveFastIn(many,{id:"n",end:now+1,hours:1,u:now},null).length===30,"keeps the latest 30");
t(T.MAX_FAST_H===168,"7 day cap");
console.log(ok,"ok",bad,"bad");
