// Recommendation first, but people can adjust calories and protein to fit them.
const fs = require("fs"), vm = require("vm");
const src = fs.readFileSync("src/App.jsx", "utf8");
const grab = (a, b) => { const i = src.indexOf(a); return src.slice(i, src.indexOf(b, i)); };
const code = "const ACTIVITY={moderate:{mult:1.55},light:{mult:1.375}};" + grab("const TAGS = {", "/* ---------- food table");
const sb = {}; vm.createContext(sb); vm.runInContext(code + ";this.T={computeTargets}", sb);
const { computeTargets } = sb.T;
let ok = 0, bad = 0; const t = (c, m) => { if (c) ok++; else { bad++; console.log("FAIL", m); } };
const p = { sex: "male", age: 35, heightIn: 70, weight: 220, goalWeight: 190, activity: "light", pace: 1 };
const rec = computeTargets(p, []);
t(computeTargets({ ...p, calAdjust: 0, proteinAdjust: 0 }, []).base === rec.base, "zero adjust = recommendation");
t(computeTargets({ ...p, calAdjust: 100 }, []).base === rec.base + 100, "+100 calories");
t(computeTargets({ ...p, calAdjust: -150 }, []).base === rec.base - 150, "-150 calories");
t(computeTargets({ ...p, proteinAdjust: 20 }, []).protein === rec.protein + 20, "+20 protein");
t(computeTargets({ ...p, proteinAdjust: -20 }, []).protein === rec.protein - 20, "-20 protein");
t(computeTargets({ ...p, calAdjust: -9999 }, []).base >= 1000, "never below 1000, even if asked");
t(computeTargets({ ...p, calAdjust: 99999 }, []).base <= rec.base + 600, "adjust capped at 600");
t(computeTargets({ ...p, calAdjust: -100 }, []).actualPace > rec.actualPace, "eating less = faster pace");
t(computeTargets({ ...p, calAdjust: -100 }, []).clamped === false, "adjusted numbers aren't 'clamped'");
const small = { sex: "female", age: 40, heightIn: 62, weight: 130, goalWeight: 120, activity: "light", pace: 2 };
t(computeTargets(small, []).clamped === true && computeTargets(small, []).base === 1200, "recommendation still held at the floor");
t(computeTargets({ ...small, calAdjust: 50 }, []).base < 1250, "own choice below the usual floor is allowed, with a warning in the UI");
const kid = { sex: "male", age: 14, heightIn: 64, weight: 130, goalWeight: 120, activity: "light", pace: 1 };
t(computeTargets({ ...kid, calAdjust: -300, proteinAdjust: -50 }, []).base === computeTargets(kid, []).base, "under 18: adjustments ignored");
t(computeTargets({ ...kid, proteinAdjust: 50 }, []).protein === computeTargets(kid, []).protein, "under 18: protein adjust ignored");
t(computeTargets({ ...p, proteinAdjust: -9999 }, []).protein >= 30, "protein floor");
const gain = computeTargets({ ...p, goalWeight: 240, pace: -0.5 }, []);
t(gain.base > gain.tdee, "gaining: eats above maintenance");
console.log(ok, "ok", bad, "bad");
