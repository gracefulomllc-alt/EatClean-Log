import { activityTip, USUAL_STEPS } from "../src/activityTip.js";
import { newSession } from "../src/training.js";
let ok = 0, bad = 0; const t = (c, m) => { c ? ok++ : (bad++, console.log("FAIL", m)); };
const base = { weightLb: 180, activity: "moderate" };
t(!activityTip({ ...base, steps: 0, sessions: [] }).has, "no activity, no card");
const a = activityTip({ ...base, steps: 8000, sessions: [] });
t(a.has && a.extraSteps === 0 && a.stepCal === 0, "steps at or under usual suggest nothing extra");
const b = activityTip({ ...base, steps: 13500, sessions: [] });
t(b.extraSteps === 13500 - USUAL_STEPS.moderate && b.stepCal > 0 && b.stepCal <= 200, "13.5k steps for a moderate person gives a small suggestion: " + b.stepCal);
t(activityTip({ ...base, steps: 30000, sessions: [] }).stepCal === 200, "step suggestion is capped at 200");
t(activityTip({ ...base, steps: 13500, sessions: [], recovering: true }).stepCal === 0, "nothing while recovering");
const lift = newSession("lift", { min: 50, effort: 3 });
const c = activityTip({ ...base, steps: 5000, sessions: [lift] });
t(c.inBudgetCal > 0 && c.inBudgetProtein === 10 && c.workouts.length === 1, "workout: already in budget, +10g protein for a hard lift: " + JSON.stringify([c.inBudgetCal, c.inBudgetProtein]));
const walk = newSession("walk", { min: 60, effort: 2 });
const d = activityTip({ ...base, steps: 14000, sessions: [walk] });
t(d.extraSteps < 14000 - USUAL_STEPS.moderate, "steps from a logged walk aren't counted twice");
t(activityTip({ ...base, steps: 5000, sessions: [lift], recovering: true }).inBudgetCal === 0, "recovering: no workout credit");
t(activityTip({ weightLb: 150, activity: "weird", steps: 12000, sessions: [] }).usual === USUAL_STEPS.moderate, "unknown activity level falls back");
console.log(bad ? `${bad} failed` : `activitytip ok (${ok})`); process.exit(bad ? 1 : 0);
